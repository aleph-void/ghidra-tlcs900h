#!/usr/bin/env python3
"""emu_assemble.py: rebuild emu_cases.py from emu_cases.src with asl (ASL=path; CPU 96C141, maximum mode).
emu_cases.src lines: name|assembly (statements separated by \\n)|initial state|expected state."""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ASL = os.environ.get('ASL', 'asl')
rows = []
with tempfile.TemporaryDirectory() as t:
    for l in open(os.path.join(HERE, 'emu_cases.src')):
        if not l.strip() or l.startswith('#'):
            continue
        name, code, init, exp = l.rstrip('\n').split('|')
        lines = [x.strip() if re.match(r'^\s*\w+:', x) else '\t' + x.strip() for x in code.split('\\n')]
        open(os.path.join(t, 'c.asm'), 'w').write('\tcpu 96c141\n\tmaxmode on\n\tsupmode on\n\torg 0\n' + '\n'.join(lines) + '\n')
        subprocess.run([ASL, '-q', '-L', '-olist', 'c.lst', 'c.asm'], cwd=t, capture_output=True, stdin=subprocess.DEVNULL)
        hx = ''
        lst = open(os.path.join(t, 'c.lst')).read()
        if re.search(r'error', lst.split('errors')[0]) and ' 0 errors' not in lst:
            sys.exit('asl error in ' + name)
        for ll in lst.splitlines():
            m = re.match(r'\s*\d+/\s*[0-9A-F]+ :((?: [0-9A-F]{2})+)', ll)
            if m:
                hx += m.group(1).replace(' ', '').lower()
        rows.append((name, code.replace('\\n', ' ; '), hx, init, exp))
out = ['"""Hand-computed p-code test sequences for the TLCS-900/H module (generated by emu_assemble.py from emu_cases.src).',
       '',
       'Expected values are worked out by hand from the Toshiba TLCS-900 CPU manual (Appendix B instruction lists: operation',
       'and SZHVNC columns; register maps; addressing-mode codes). The machine code was assembled from the source shown',
       'with asl (CPU 96C141, maximum mode) and is kept here as hex.',
       'Registers by name (XWA, WA, A, ..., XWA_1 = bank-1 storage, F = flags S Z - H - V N C, SR); memory items',
       'n<size>:<addr>=hex are little-endian. "@NN" in an expectation is the case\'s own address + NN (8 hex digits).',
       'A case named XFAIL_* carries a deliberately wrong expectation that must be reported.',
       '"""',
       'CASES = [']
for name, code, hx, init, exp in rows:
    out.append(f'    # {code}')
    out.append(f'    ({name!r}, {hx!r}, {init!r}, {exp!r}),')
out.append(']')
open(os.path.join(HERE, 'emu_cases.py'), 'w').write('\n'.join(out) + '\n')
print(len(rows), 'cases')
