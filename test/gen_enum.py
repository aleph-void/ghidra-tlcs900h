#!/usr/bin/env python3
"""gen_enum.py <out.bin>: structured corpus of 8-byte slots that reaches every SLEIGH constructor: every addressing
prefix (each memory form and size, short and extended register forms, several register-code classes) followed by every
operation byte and a few operand-byte patterns, plus the one-byte op codes."""
import sys

PREFIXES = []
for base in (0x80, 0x90, 0xa0, 0xb0):
    PREFIXES += [[base + 3], [base + 5], [base + 8, 0x10], [base + 8, 0xf0]]
for base in (0xc0, 0xd0, 0xe0, 0xf0):
    PREFIXES += [[base, 0x40], [base + 1, 0x34, 0x12], [base + 2, 0x56, 0x34, 0x12],
                 [base + 3, 0xe8], [base + 3, 0x10], [base + 3, 0xd4], [base + 3, 0xf0],
                 [base + 3, 0xe9, 0x10, 0x00], [base + 3, 0xe9, 0xf0, 0xff], [base + 3, 0x05, 0x34, 0x12],
                 [base + 3, 0x03, 0xe8, 0xe1], [base + 3, 0x03, 0x14, 0x02], [base + 3, 0x03, 0xd8, 0xd1],
                 [base + 3, 0x07, 0xec, 0xe4], [base + 3, 0x07, 0x24, 0x36], [base + 3, 0x07, 0xd0, 0xd2],
                 [base + 4, 0xe1], [base + 4, 0x12], [base + 4, 0xd8], [base + 5, 0xe2], [base + 5, 0x20], [base + 5, 0xdc]]
for base in (0xc8, 0xd8, 0xe8):
    PREFIXES += [[base + r] for r in range(8)]
for p in (0xc7, 0xd7, 0xe7):
    for code in (0xe0, 0xe2, 0xe4, 0xf0, 0xf8, 0x00, 0x14, 0x26, 0x38, 0xd0, 0xd4, 0xdc, 0xe1, 0xe3, 0x01):
        PREFIXES.append([p, code])
TAILS = [[0x03, 0x00, 0x00, 0x00, 0x00], [0x05, 0x12, 0x34, 0x00, 0x00], [0x00, 0x80, 0x00, 0x00, 0x00],
         [0x22, 0x00, 0x00, 0x00, 0x00], [0x3c, 0x00, 0x00, 0x00, 0x00], [0x10, 0x00, 0x00, 0x00, 0x00]]
out = bytearray()


def slot(b):
    out.extend(bytes(b[:8]).ljust(8, b'\0'))


for p in PREFIXES:
    for op in range(256):
        for t in TAILS:
            slot(p + [op] + t)
for op in range(256):
    for t in TAILS + [[0xff] * 5, [0x07, 0x00, 0x00]]:
        slot([op] + t)
for p in PREFIXES:
    if p[0] in (0xc7, 0xd7, 0xe7) or p[0] & 0x0f >= 8 and p[0] >= 0xc8:
        for op in (0x2e, 0x2f):
            for cr in list(range(0, 0x30, 2)) + [0x3c]:
                slot(p + [op, cr])
slot([0xf7, 0x00, 0x12, 0x00, 0x34, 0x00])
for r in range(0x20, 0x40):
    slot([0xf3, 0x13, 0x10, 0x00, r])
    slot([0xf3, 0x13, 0xf0, 0xff, r])
open(sys.argv[1], 'wb').write(out)
print(len(out) // 8, 'slots')
